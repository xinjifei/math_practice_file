"""Day 15 三个实验 —— 理解 p 值的行为"""
import numpy as np
from scipy.stats import ttest_1samp

# ============================================================
# 实验 1：真正没用的策略，p < 0.05 的概率是多少？
# ============================================================
print("=" * 50)
print("实验1: 没用策略的误判率")
print("=" * 50)

np.random.seed(42)           # 固定随机数，每次运行结果一样
false_count = 0              # 记录"误判为有效"的次数

for _ in range(10000):                    # 重复 10000 次实验
    trades = np.random.normal(0, 1, 30)   # 生成 30 笔交易，期望收益 = 0（完全没用）
    _, p = ttest_1samp(trades, popmean=0) # 检验：这 30 笔收益像不像是"有用策略"？
    if p < 0.05:                          # p < 0.05 → 被误判为"有效"
        false_count += 1

print(f"10000 次中 p<0.05 的次数: {false_count}")
print(f"误判率: {false_count/10000:.1%}")
print(f"→ 没用策略也有约 5% 的概率'看起来有效'\n")


# ============================================================
# 实验 2：有用的弱策略，交易笔数越多，p 值怎么变？
# ============================================================
print("=" * 50)
print("实验2: p 值随交易笔数的变化")
print("=" * 50)

# 模拟：每笔交易期望赚 0.1%（真有用），但标准差 2%（波动大）
# 信号很弱，需要很多笔才能从噪声里浮现出来

np.random.seed(42)

for n in [5, 10, 30, 100, 300, 1000]:        # 不同交易笔数
    trades = np.random.normal(0.1, 2, n)       # n 笔交易，每笔期望 +0.1%
    _, p = ttest_1samp(trades, popmean=0)      # 检验：这 n 笔收益像不像是"有用策略"？
    print(f"交易 {n:>4} 笔: p = {p:.4f}")       # p 值本身——越小越说明信号强
    #                                                                   ↑
    #                                           交易多了，p 值往下走 → 噪声被平均掉，信号浮现


# ============================================================
# 实验 3：多重检验灾难 —— 测 100 个没用策略，几个"显著"？
# ============================================================
print("=" * 50)
print("实验3: 多重检验灾难")
print("=" * 50)

np.random.seed(42)
n_strategies = 100            # 测 100 个策略
sig_list = []                 # 存放每个策略的 p 值

for _ in range(n_strategies):
    trades = np.random.normal(0, 1, 50)   # 每个策略 50 笔交易，期望 = 0（全没用）
    _, p = ttest_1samp(trades, popmean=0) # 检验
    sig_list.append(p)

# 数一数 p < 0.05 的有几个
sig_count = sum(1 for p in sig_list if p < 0.05)
print(f"100 个完全没用的策略中，'显著'的有: {sig_count} 个")
print(f"→ 这 {sig_count} 个全是运气砸出来的假阳性")
print(f"→ 翻 1000 个因子，大约 50 个'显著'——但可能全是噪声")
