# -*- coding: utf-8 -*-
"""
demo_matrix.py —— 「矩阵 = 变换机器」的参考脚手架

注意：这里的数据和练习不一样！
  练习：M=[[1,0],[0,-1]]（上下翻转），要猜 [[0,1],[1,0]]（交换坐标）
  本 demo：M=[[2,0],[0,2]]（整体放大 2 倍），v=[2,1]

目的：看懂「矩阵 × 向量 = 新向量」这个"变换"思路，再自己动手做练习。
"""

import numpy as np
from function.plot import plot_vectors


# ── 第 1 步：定义一个 2×2 矩阵 ────────────────────
# 矩阵 = 数字表格。np.array 里套两个列表 = 两行两列。
#   [[2, 0],    ← 第 1 行
#    [0, 2]]    ← 第 2 行
M = np.array([[2, 0],
              [0, 2]])

# ── 第 2 步：定义一个向量（箭头） ──────────────────
v = np.array([2, 1])   # 从原点指向点 (2, 1)


# ── 第 3 步：矩阵 × 向量 = 新向量 ─────────────────
# @ 是 Python 里的「矩阵乘法」运算符（读作 at）。
# M @ v = 把向量 v 送进"变换机器" M，吐出一个新向量 w。
w = M @ v

print("原始向量 v =", v)
print("变换后的向量 w =", w)


# ── 这个矩阵做了什么？ ──────────────────────────
# 矩阵×向量 的规则：结果 w 的每个坐标 = M 的每一行 与 v 做「点积」。
#   （这正好串上你 Day 27 学的点积！）
#   第 1 行 [2, 0] · [2, 1] = 2×2 + 0×1 = 4   → w 的第 1 个坐标
#   第 2 行 [0, 2] · [2, 1] = 0×2 + 2×1 = 2   → w 的第 2 个坐标
#   所以 [2, 1] → [4, 2]：每个坐标都 ×2 = 整体放大 2 倍。
#
# 结论：[[2,0],[0,2]] 这个矩阵，作用就是「把任何向量放大 2 倍」。


# ── 画图对比：变换前 v vs 变换后 w ────────────────
# plot_vectors 输入 = [{"名字": [x, y]}, ...]，title 是标题
plot_vectors(
    [
        {"v(原始)": list(v)},        # (2, 1)
        {"w(放大2倍)": list(w)},     # (4, 2)
    ],
    title="矩阵 [[2,0],[0,2]] = 放大 2 倍",
)
