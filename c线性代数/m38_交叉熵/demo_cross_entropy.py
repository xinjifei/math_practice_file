# demo_cross_entropy.py
# 演示：交叉熵的最小骨架 —— 拿"模型预测的分布"去量"真实事件"的意外程度。
#
# ⚠️ 演示用的真实分布是 [0,1,0]（正确答案在第 2 类），预测数据和曲线也都和你练习不同。
#    你练习时用真实 = [1,0,0]，预测 [0.9,0.05,0.05] / [0.6,0.2,0.2] / [0.1,0.5,0.4]，
#    曲线画二分类 H([1,0], [p, 1-p])——骨架一模一样，数据全不同。
#
# 全程用 log2（单位 = bit），跟 m37 的 note 保持一致。换成 ln 只差一个常数倍。

import numpy as np
from function.plot import plot


# ---- 1. 两个函数：熵（Day 37 那个）和交叉熵（今天） ----
def entropy(p):
    """熵 H(p)：拿分布 p 自己量自己。Day 37 学的，这里留着做对比。"""
    p = np.asarray(p, dtype=float)      # 统一转成 numpy 数组，后面才能逐元素算
    safe = np.where(p > 0, p, 1.0)      # log2(0) = -inf，把 0 顶成 1.0 挡掉
    return -np.sum(p * np.log2(safe))


def cross_entropy(p, q):
    """交叉熵 H(p, q)：p = 真实分布，q = 模型预测。

    公式：H(p, q) = -Σ pᵢ · log(qᵢ)
        和 m37 的熵只差一个字符 —— log 里面装的是 **q**（预测），不是 p（真实）。
        直觉：真实事件按 pᵢ 的频率出现；每出现一次，就用 q 给它打一个"意外分"
              -log(qᵢ)。再按 pᵢ 加权平均，就是交叉熵。

    关键：p 只决定"哪几类参与、各占多少权重"；真正进 log 的是 q。
          所以 q 给正确那一类的概率越低 → 这一项越大 → 交叉熵越大。
    """
    p = np.asarray(p, dtype=float)
    q = np.asarray(q, dtype=float)
    # 同样的 0 问题：log2(0) = -inf。
    # qᵢ = 0 的意思是"模型说这件事绝不可能"，如果真实恰好就是它，交叉熵应该是 +∞。
    # 下面把 0 顶成 1.0 只是防止程序算出 inf/nan 崩掉 —— 这是简化，真实框架不会这么写。
    # 本演示的数据里 q 全都 > 0，碰不到这个坑。
    safe_q = np.where(q > 0, q, 1.0)
    return -np.sum(p * np.log2(safe_q))


# ---- 2. 真实标签是 one-hot 时，交叉熵退化成"给正确类打的分" ----
# one-hot：只有一个位置是 1，其余全是 0。分类任务的真实标签就长这样。
p_true = [0.0, 1.0, 0.0]        # 正确答案 = 第 2 类

# 三组预测，越往下越离谱。盯住第 2 项 —— 那是模型给"正确答案"的概率。
preds = {
    "很准 [0.1, 0.8, 0.1]": [0.1, 0.8, 0.1],
    "一般 [0.3, 0.4, 0.3]": [0.3, 0.4, 0.3],
    "很差 [0.6, 0.2, 0.2]": [0.6, 0.2, 0.2],
}

for name, q in preds.items():
    print(f"{name:22s}  交叉熵 = {cross_entropy(p_true, q):.4f}")

# 结果：0.3219 / 1.3219 / 2.3219 —— 一路变大，跟"给正确类的概率" 0.8 / 0.4 / 0.2 反着走。
# 原因：p 只有第 2 项是 1，求和里别的项都被 pᵢ = 0 乘没了，只剩一项：
#     H(p, q) = -1 × log2(q₂) = -log2(模型给正确类的概率)
# 手算对一下：-log2(0.8) = 0.3219 ✓
# 这就是 LLM 训练 loss 的真身：模型给正确答案的概率越高，loss 越小。


# ---- 3. 真实分布不是 one-hot 时，能看出交叉熵的"下限" ----
# 真实分布不必是 one-hot（比如"这张图 50% 是猫、30% 是狗、20% 是鸟"）。
# 这时交叉熵有个硬下限：H(p, q) ≥ H(p) —— 不可能比真实分布自己的熵还低。
# 高出来的那截就是"预测不准的代价"（它有个名字叫 KL 散度，今天不用管）。
p_real = [0.5, 0.3, 0.2]

print(f"\n真实分布 p = {p_real}")
print(f"它自己的熵 H(p) = {entropy(p_real):.4f}   ← 交叉熵再厉害也不能低于这个数")
print()

candidates = {
    "q = p（猜得完全准）": [0.5, 0.3, 0.2],
    "q = 均匀（不猜了）": [1 / 3, 1 / 3, 1 / 3],
    "q = 把 1、3 类搞反": [0.2, 0.3, 0.5],
}
for name, q in candidates.items():
    print(f"{name:22s}  交叉熵 = {cross_entropy(p_real, q):.4f}")

# 结果：1.4855（正好 = H(p)，取等）/ 1.5850 / 1.8821。三条结论：
#   ① q 完全等于 p 时，交叉熵 == 熵 → 熵就是交叉熵能压到的最低点
#   ② "均匀"比"完全猜对"差，但还不是最差 —— 至少没押错方向
#   ③ "把概率搬反"最差：它把 0.5 押在了错误的类上，比"不表态"罚得更重


# ---- 4. 画曲线：正确类的概率一路涨上去，交叉熵怎么掉 ----
# 设定：真实 = [0, 1, 0]；预测 = [(1-t)/2, t, (1-t)/2]。
# t 就是"模型给正确类的概率"，剩下两类永远均分。让 t 从 0 走到 1。
# 代入公式只剩一项：H = -log2(t) → t 越大交叉熵越小，t = 1 时正好是 0。
# 先猜形状：t 小的时候爆炸（模型笃定地猜错，代价趋于无穷），t 靠近 1 时贴着 0 往下溜。
ts = np.linspace(0.05, 1.0, 96)     # 从 0.05 起 —— 从 0 起会算出 +inf，画不出来

curve = []                          # 每个元素是 [t, 交叉熵]，等一下画图要用
for t in ts:
    pred = [(1 - t) / 2, t, (1 - t) / 2]
    curve.append([t, cross_entropy([0.0, 1.0, 0.0], pred)])

curve = np.array(curve)             # (96, 2) 矩阵：第 0 列 = t，第 1 列 = 交叉熵

# 顺手标两个 t，看看它们落在曲线的什么位置
for t_mark in (1 / 3, 0.5):
    pred = [(1 - t_mark) / 2, t_mark, (1 - t_mark) / 2]
    print(f"\nt = {t_mark:.4f} → 交叉熵 = {cross_entropy([0.0, 1.0, 0.0], pred):.4f}")
# t = 1/3 时预测恰好是均匀分布 → 1.5850，就是上一段那个"不猜了"的值
# t = 1/2 时 → 1.0000，正好 1 bit

# 用统一的 plot()：point 层，data 必须是 (n, 2) 矩阵，每行一个 [x, y]。
# s = 点的大小 —— 96 个点，调小一点连起来才像一条曲线。
plot(
    [{"type": "point",
      "data": curve,
      "color": "tab:orange",
      "s": 8}],
    title="交叉熵随「模型给正确类的概率」上升而下降",
)
