# -*- coding: utf-8 -*-
"""
demo_eigen.py —— 特征向量与特征值的最小可运行示例

今天要回答的核心问题：
    矩阵作用在大多数向量上，方向 + 长度都变；
    但对某些特殊向量（特征向量），只变长度、不变方向。
    那个"长度变化的倍数"就是特征值。

下面用一个能"手算验证"的 2×2 矩阵演示，方便你对照 np.linalg.eig 的输出。
"""

import numpy as np

# 一个对称矩阵（对称 → 特征值一定是实数，特征向量互相垂直，最好观察）
# A = [[2, 1],
#      [1, 2]]
# 它有两个特征向量方向：
#   v1 = (1, 1) 方向 → 特征值 λ1 = 3  （A@v1 = (3, 3) = 3 * v1，方向不变，拉长 3 倍）
#   v2 = (1, -1) 方向 → 特征值 λ2 = 1  （A@v2 = (1, -1) = 1 * v2，方向不变，长度也不变）
A = np.array([[2, 1],
              [1, 2]])

print("矩阵 A =")
print(A)
print()

# ---- np.linalg.eig 一次算出 特征值 + 特征向量 ----
# eig(A) 返回两个东西：
#   eigenvalues : 一维数组，每个元素是一个特征值
#   eigenvectors: 二维数组，每一"列"是对应那个特征值的特征向量（已经归一化成长度 1）
eigenvalues, eigenvectors = np.linalg.eig(A)

print("特征值 (eigenvalues) =", eigenvalues)
# 输出 [3. 1.]  → λ 从大到小：3 是"重要方向"，1 是"次要方向"

print()
print("特征向量 (eigenvectors)，每一列对应一个特征值 =")
print(eigenvectors)
# 第一列 ≈ [0.707, 0.707] = (1,1) 方向，对应 λ=3
# 第二列 ≈ [0.707, -0.707] = (1,-1) 方向，对应 λ=1
# （0.707 = 1/√2，只是把 (1,1) 缩成了单位长度，方向没变）
print()

# ---- 验证核心关系：A @ v == λ * v ----
# 取第一个特征向量（第一列），和第一个特征值
v = eigenvectors[:, 0]          # 第一列
lam = eigenvalues[0]            # 第一个特征值

print("验证 A @ v 是否等于 λ * v：")
print("A @ v    =", A @ v)      # 矩阵作用在特征向量上
print("λ * v    =", lam * v)    # 特征值 × 特征向量
print("相等吗？ ", np.allclose(A @ v, lam * v))   # np.allclose 判断两者数值上是否几乎相等
print()

# ---- 对比：普通向量，方向会被改变 ----
u = np.array([1, 0])            # 随便取一个普通向量 (1,0)
print("普通向量 u =", u)
print("A @ u    =", A @ u)      # 变成 (2,1)，方向已经不在原来的 x 轴上了
print("注意：(1,0) 变成了 (2,1)，方向变了 —— 它不是特征向量")
