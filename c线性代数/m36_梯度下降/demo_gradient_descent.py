# demo_gradient_descent.py
# 演示：梯度下降的最小骨架 —— 反复执行"参数 ← 参数 - 学习率 × 梯度"，让损失变小。
#
# ⚠️ 演示用的函数是 f(x) = (x-1)²，起点 x=4，lr=0.2，只迭代 6 次（能手算核对）。
#    你练习时换成 h(x) = (x+2)²，起点 x=5，lr = 0.1 / 1.2 / 0.01，迭代 15 次——
#    骨架一模一样，函数、起点、学习率全都不同。

import numpy as np
from function.plot import plot


# ---- 1. 先定义两个东西：损失函数、它的梯度 ----
# 损失函数 = "我现在离目标有多远"的打分器。越小越好。
def loss(x):
    """输入一个 x，输出一个数：离目标有多远。目标在 x=1（那里 (x-1)² = 0）。"""
    return (x + 2) ** 2


def grad(x):
    """梯度：损失函数在当前 x 处"最陡上升"的方向。

    对 f(x) = (x-1)²，求导得 f'(x) = 2(x-1)。
    一维情况下"梯度"退化成一个数，正负号就代表方向：
        grad(4) =  6 > 0  →  往右走损失变大  →  所以该往左走
        grad(0) = -2 < 0  →  往左走损失变大  →  所以该往右走
    "沿梯度方向走 = 损失上升最快"，在这个一维例子里一眼就能看出来。
    ⚠️ 真实项目里这个函数不用你写——PyTorch 的 autograd 自动算。这里手写是为了看清机制。
    """
    return 2 * (x + 2)


# ---- 2. 梯度下降的主循环 ----
x = 5.0          # 起点：随便站在山坡上某个位置
lr = 0.1         # 学习率：每一步迈多大
steps = 6        # 迭代多少次

curve = []       # 记录每一步的 [迭代次数, 损失]，等一下画图要用
for i in range(steps):
    # range(steps) 依次给出 0,1,2,3,4,5，i 只用来计数

    # 先记录"这一步开始时的状态"：站在哪、损失多少
    curve.append([i, loss(x)])
    print(f"第 {i} 步：x = {x:.5f}   loss = {loss(x):.5f}")

    # ↓↓↓ 整个梯度下降，就这一行 ↓↓↓
    x = x - lr * grad(x)
    # 为什么是"减"？因为 grad(x) 指向损失变大的方向，我们要损失变小 → 朝反方向走。
    # lr 的作用是"步长"：grad 只告诉你朝哪走，lr 说你这一步迈多远。

# 循环结束后，记录最终落点
curve.append([steps, loss(x)])
print(f"第 {steps} 步：x = {x:.5f}   loss = {loss(x):.5f}")


# ---- 3. 为什么是这个收敛速度？（把更新式展开看） ----
#   x ← x - 0.2 × 2(x - 1)
#     = x - 0.4x + 0.4
#     = 0.6x + 0.4
# 再看"到目标的距离" |x - 1|：
#   新距离 = |0.6x + 0.4 - 1| = |0.6x - 0.6| = 0.6 × |x - 1| = 0.6 × 旧距离
#
# 结论：每迭代一次，到谷底的距离就被乘上 0.6。0.6 < 1 → 越走越近 = 收敛。
# 这个"每步乘上的因子"就是判断收敛还是发散的判据（练习里的 lr=1.2 会让它变成 -1.4）。
# 另外注意：梯度本身在变小（x 越靠近 1，2(x-1) 越小），所以每步实际迈出的距离也在缩小
# —— 这就是为什么曲线后面越来越平。曲线变平不是"卡住了"，是快到谷底了。

# ---- 4. 用统一的 plot() 画收敛曲线 ----
# 思路：X 轴 = 迭代次数，Y 轴 = 损失。每个点代表一次迭代的状态。
#   point 层的 data 必须是 (n, 2) 矩阵，每行一个 [x, y]。
#   训练循环里用的是普通 Python list，画图时转成 numpy 数组即可。
curve = np.array(curve)          # 7 行 2 列：第 0 列是迭代次数，第 1 列是 loss

plot(
    [{"type": "point",
      "data": curve,             # (7, 2) 矩阵，直接喂给 point 层
      "color": "tab:red",
      "s": 30}],                 # s = 点的大小（透传给 scatter 的参数）
    title="梯度下降：loss 随迭代次数下降",
)
# plot() 内部会自动定坐标轴范围、画参考轴和网格，不用自己 set_xlim。
