"""
demo_transpose.py —— 转置矩阵参考脚手架

今天核心一句话：Q @ K.T 的 [i][j] = Q 第 i 行 与 K 第 j 行 的点积 = 相似度分数。

⚠️ 这是参考 demo，用的是【不同】的数据（3×2 的 Q、K）。
   你的练习要用 2×3 的 Q、K，自己动手写、自己验证——别照抄数据。
"""

import numpy as np  # numpy：Python 的数值计算库，矩阵/数组运算都靠它

# ── 1. 创建 Q 和 K（这里用 3×2，和你练习里的 2×3 不同）─────────────
# np.array([[...], [...], ...]) 把「列表套列表」变成一个二维数组（矩阵）。
# 参数：一个嵌套列表——外层列表的每个元素 = 矩阵的一行。
Q = np.array([
    [1, 2],   # Q 的第 0 行 —— 一个 query（查询向量），长度 2
    [3, 4],   # Q 的第 1 行
    [5, 0],   # Q 的第 2 行
])  # 形状 (3, 2)：3 个 query，每个是 2 维向量

K = np.array([
    [2, 1],   # K 的第 0 行 —— 一个 key（键向量），长度 2
    [0, 1],   # K 的第 1 行
    [1, 1],   # K 的第 2 行
])  # 形状 (3, 2)：3 个 key，每个是 2 维向量

# .shape：数组的属性，返回形状元组 (行数, 列数)。用来确认维度对不对。
print("Q 的形状:", Q.shape)   # (3, 2)
print("K 的形状:", K.shape)   # (3, 2)

# ── 2. 转置 K ─────────────────────────────────────────────────────
# .T：转置属性。沿对角线「翻面」，行变列、列变行。
# K (3×2) → K.T (2×3)
K_T = K.T
print("\nK.T 的形状:", K_T.shape)  # (2, 3)

# ── 3. 矩阵乘法 Q @ K.T ──────────────────────────────────────────
# @：矩阵乘法运算符（Python 3.5+），等价于 np.matmul(Q, K_T)。
# 相乘前提：左边列数 == 右边行数。Q (3×2) 的列 2 == K.T (2×3) 的行 2 ✓
# 结果形状 = (左行数, 右列数) = (3, 3)：3 个 query × 3 个 key 的「相似度矩阵」
S = Q @ K.T
print("\nQ @ K.T 相似度矩阵:\n", S)

# ── 4. 验证：S[i][j] 必须等于 Q 第 i 行 与 K 第 j 行 的点积 ─────────
# np.dot(v, w)：计算两个一维向量的点积 v₁w₁ + v₂w₂ + ...。
# 参数：两个一维数组，返回一个标量（数字）。
# Q[0] = Q 的第 0 行 = [1, 2]；K[2] = K 的第 2 行 = [1, 1]
# 手算：1×1 + 2×1 = 3，应该等于 S[0][2]。
check = np.dot(Q[0], K[2])
print("\n验证 S[0][2]：")
print("  np.dot(Q[0], K[2]) =", check)
print("  S[0][2]            =", S[0][2])
print("  相等?", check == S[0][2])   # 应该打印 True

