# demo_matrix_multiply.py
# 参考脚手架：矩阵乘法 = 变换的叠加（结合律 + 不可交换）
# 注意：这里用的是「旋转 + 拉伸」这组数据，和你的练习（翻转 + 拉伸）不同。
#       思路一样，但别直接照抄——你的练习要自己用 A=[[1,0],[0,-1]] 和 B=[[2,0],[0,1]] 重做一遍。

import numpy as np

# ---- 0. 准备两个"变换"和一个向量 ----
# R = 逆时针旋转 90° 的矩阵。
#     矩阵的每一列 = 对应基向量被变换后的位置：
#     第一列 [0,1] 是 (1,0) 转完后的位置，第二列 [-1,0] 是 (0,1) 转完后的位置。
R = np.array([[0.0, -1.0],
              [1.0,  0.0]])

# S = 拉伸矩阵：x 方向拉长 3 倍，y 方向压到 0.5 倍。
S = np.array([[3.0, 0.0],
              [0.0, 0.5]])

# v = 一个待变换的向量（随便挑一个，和练习里的 v 不同）
v = np.array([2.0, 1.0])

# ---- 1. 结合律：先 S 变换 v、再 R 变换结果 == 直接用 (R@S) 一次性变换 ----
# R@(S@v)：分两步——先把 v 拉伸，再把结果旋转
stepwise = R @ (S @ v)
# (R@S)@v：先把两个变换"合成"成一个复合矩阵（先 S 后 R），再一次性作用在 v 上
composite = (R @ S) @ v

print("分步 R@(S@v)：", stepwise)
print("合成 (R@S)@v：", composite)

# np.allclose(a, b)：逐个元素比较 a 和 b，允许极小浮点误差，全相等返回 True。
# 这里返回 True 就证明 (R@S)@v == R@(S@v)，即矩阵乘法满足结合律。
print("结合律成立？", np.allclose(stepwise, composite))

# ---- 2. 交换律：R@S 和 S@R 顺序不同，结果不同 ----
RS = R @ S   # 先拉伸、再旋转
SR = S @ R   # 先旋转、再拉伸

print("\nR@S（先拉伸后旋转）=\n", RS)
print("S@R（先旋转后拉伸）=\n", SR)

# 两个矩阵逐元素是否相等？False 说明不可交换——顺序换了，结果就变了。
print("R@S == S@R ？", np.allclose(RS, SR))
