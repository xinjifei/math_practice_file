# -*- coding: utf-8 -*-
# demo_portfolio_risk.py
# 演示：两只股票放进同一个组合，组合的风险怎么由两只股票拼出来。
#
#   组合期望收益 = w₁·μ₁ + w₂·μ₂                        ← 就是加权平均，没有花活
#   组合方差     = w₁²σ₁² + w₂²σ₂² + 2·w₁·w₂·ρ·σ₁·σ₂     ← 今天的主角
#                    └自身┘   └自身┘   └─ 协方差项 ─┘
#
# 核心想让你看到的一件事：ρ（相关系数）一降，第三项就变小，组合风险跟着往下掉，
# 而第一、二项完全不动。ρ = 1 时组合风险恰好等于加权平均，ρ < 1 就一定更低。
#
# ⚠️ 演示参数：C(μ=6%, σ=15%)、D(μ=10%, σ=25%)，权重 60/40。
#    练习要的是 A(8%, 20%)、B(12%, 30%)、50/50、ρ = −0.5/0/0.5 ——
#    数字完全不同，别把 demo 的输出当成练习的答案。

import numpy as np
from function.plot import plot


# ---- 参数（全集中在开头） ----
MU_C, SIG_C = 0.06, 0.15     # 股票 C：期望年收益 6%，年波动 15%
MU_D, SIG_D = 0.10, 0.25     # 股票 D：期望年收益 10%，年波动 25%
W_C, W_D = 0.6, 0.4          # 权重：60% 的钱买 C，40% 买 D


def portfolio_risk(w1, sig1, w2, sig2, rho):
    """给定权重、两只股票的 σ 和相关系数 ρ，返回组合的风险 σ_p。

    参数:
        w1, w2    : 两个权重；正常情况下加起来 = 1
        sig1, sig2: 两只股票各自的标准差（风险）
        rho       : 相关系数，范围 [−1, 1]，ρ = Cov / (σ₁·σ₂)
    返回:
        组合的标准差（风险），不是方差 —— 量纲和单只股票的 σ 一致，才能直接比。
    """
    # 第 1、2 项：各自的风险，按"权重的平方"缩放。
    # 注意是平方 —— 因为方差是平方量纲，权重进方差也要平方。
    own = (w1 ** 2) * (sig1 ** 2) + (w2 ** 2) * (sig2 ** 2)

    # 第 3 项：协方差项 = 2 · w₁ · w₂ · Cov，而 Cov = ρ · σ₁ · σ₂。
    #   ρ > 0 → 同涨同跌 → 这一项加风险
    #   ρ = 0 → 各走各路 → 这一项为 0
    #   ρ < 0 → 一个涨一个跌 → 这一项是负的，倒过来抵消前三项
    cross = 2 * w1 * w2 * rho * sig1 * sig2

    # np.sqrt(...)：开平方。方差 → 标准差。
    return np.sqrt(own + cross)


# ---- 1. 期望收益和"没有分散化时"的基准 ----
exp_ret = W_C * MU_C + W_D * MU_D          # 加权平均，ρ 怎么变它都不动
wavg_sig = W_C * SIG_C + W_D * SIG_D        # 加权平均风险：ρ = 1 时组合正好是这个值

print("【1】组合的期望收益与基准风险")
print(f"  期望收益     {exp_ret:.2%}   ← 无论 ρ 是多少，永远是加权平均")
print(f"  加权平均风险 {wavg_sig:.2%}   ← ρ = 1 时组合风险正好等于它（一点好处都没有）")


# ---- 2. 只看几个关键 ρ，把三项摊开 ----
print("\n【2】三种 ρ 下，组合方差的三项")
print(f"  {'ρ':>5}  {'自身项':>8}  {'协方差项':>9}  {'组合方差':>9}  {'组合风险':>8}")
for rho in [-1.0, -0.5, 0.0, 0.5, 1.0]:
    own = (W_C ** 2) * (SIG_C ** 2) + (W_D ** 2) * (SIG_D ** 2)
    cross = 2 * W_C * W_D * rho * SIG_C * SIG_D
    var = own + cross
    print(f"  {rho:>5.1f}  {own:>8.4f}  {cross:>+9.4f}  {var:>9.4f}  {np.sqrt(var):>8.2%}")

# 盯住上面这张表的三件事：
#   ① 自身项从头到尾一动不动 —— 分散化不改变单个资产的风险
#   ② 协方差项随 ρ 线性下滑，从正到负，把组合风险一路往下拽
#   ③ ρ = 1 那行，组合风险 = 19.00% = 加权平均，一分钱好处都没有


# ---- 3. 把 ρ 从 −1 扫到 1，画出整条曲线 ----
# np.linspace(start, stop, num)：在 [start, stop] 上均匀取 num 个数（含两端）。
rho_grid = np.linspace(-1, 1, 41)      # 41 个 ρ

# 列表推导：对每个 ρ 调一次上面的函数，得到 41 个组合风险。
risk_grid = np.array([portfolio_risk(W_C, SIG_C, W_D, SIG_D, r) for r in rho_grid])

# np.column_stack([列A, 列B])：把两个一维数组按列拼成 (n, 2) 矩阵。
#   line 层要的就是这个形状：每行一个顶点 [x, y]，按行顺序连成折线。
#   这里 y 乘 100 换成百分数 —— plot() 会给上下各留 1 的边距，
#   风险是 0.1 量级的数，不放大成百分数会被压成一条贴底的直线。
curve_layer = {
    "type": "line",
    "data": np.column_stack([rho_grid, risk_grid * 100]),
    "color": "tab:blue",
    "linestyle": "-",                 # 组合风险画实线
}

# 加权平均风险的参考线：横着一条，x 从 −1 到 1，y 恒为 wavg_sig。
#   line 层至少要 2 个点才连得成线，所以给首尾两个点。
bench_layer = {
    "type": "line",
    "data": np.array([[-1.0, wavg_sig * 100], [1.0, wavg_sig * 100]]),
    "color": "tab:gray",
    "linestyle": "--",                # 基准画虚线，和真实曲线分开
}

# 在 ρ = 1 的端点标一个点，让你一眼看出曲线正好落在那条参考线上。
end_layer = {
    "type": "point",
    "data": np.array([[1.0, risk_grid[-1] * 100]]),
    "labels": [f"ρ=1 → {risk_grid[-1]:.2%}"],
    "color": "tab:red",
    "s": 60,                          # 点的面积
}

plot([curve_layer, bench_layer, end_layer],
     title="ρ 从 −1 到 1：组合风险（%）与加权平均基准（虚线）")

