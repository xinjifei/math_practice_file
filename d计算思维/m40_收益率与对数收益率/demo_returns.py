# demo_returns.py
# 演示：同一个"赚了多少"，有两种算法 —— 简单收益率 和 对数收益率。
#
#   简单：r     = (P₁ - P₀) / P₀      ← 口袋里的钱变了百分之几，日常用
#   对数：r_log = ln(P₁ / P₀)         ← 数学分析用，三个优势：可加、对称、接近正态
#
# ⚠️ 演示用一条【手写的 10 天】价格路径（前段小波动、后段大波动）。
#    你练习要自己模拟【两组 30 天】股价（小波动一组 / 大波动一组）。数据完全不同。

import numpy as np
from function.plot import plot


# ---- 1. 先在一串"涨跌幅"上直接对比两个公式 ----
# 关键近似：r_log = ln(1 + r) ≈ r —— 但只在 r 小的时候成立。看数字。
rs = np.array([0.001, 0.01, 0.05, 0.2, 0.5])   # 五档涨跌幅：从千分之一到腰斩

# np.log1p(x)：等价于 ln(1 + x)，但专门为"x 很小"的场景设计 ——
#   直接算 np.log(1 + 0.001) 会先把 1.001 存成浮点数，丢掉精度再取对数；
#   log1p 内部绕开了这一步，小 x 时更准。这是个"知道有更好写法"就够的细节（可外包）。
r_logs = np.log1p(rs)

print("　涨跌幅 r　　对数 r_log　　　　两者之差")
for r, rl in zip(rs, r_logs):
    print(f"{r:>8.3f}　{rl:>12.8f}　{r - rl:>14.8f}")
# 看出来了吗：r = 0.001 时差 0.0000005（肉眼不可见），r = 0.5 时差 0.09（差出小半个身位）。
# 这就是"小波动时两条线贴在一起、大波动时裂开"的全部原因。


# ---- 2. 可加性：对数收益能直接相加，简单收益率不能 ----
# 造一条 4 天的价格：100 → 110 → 99 → 108.9
p = np.array([100.0, 110.0, 99.0, 108.9])

r_daily = (p[1:] - p[:-1]) / p[:-1]   # 每天的简单收益率。p[1:] 是"今天"，p[:-1] 是"昨天"
r_log_daily = np.log(p[1:] / p[:-1])  # 每天的对数收益率

print(f"\n每天的简单收益率：{np.round(r_daily, 6)}")
print(f"每天的　对数收益率：{np.round(r_log_daily, 6)}")

total_r = (p[-1] - p[0]) / p[0]       # 这三天的"总简单收益率"：从 100 到 108.9
total_log = np.log(p[-1] / p[0])      # 这三天的"总对数收益率"

print(f"\n总简单收益率 = {total_r:.6f}　　而三天简单收益率相加 = {r_daily.sum():.6f}　← 对不上")
print(f"总　对数收益率 = {total_log:.6f}　　而三天　对数收益率相加 = {r_log_daily.sum():.6f}　← 完全相等")
# 差在哪：简单收益率是"相对于各自的起点"算的，起点天天在变，加起来的基准根本不统一。
# 对数收益率算的是"倍率的对数"，倍率可以直接乘，取完对数就变成直接加。


# ---- 3. 对称性：涨和跌，两种算法报出来的数不一样 ----
# 100 → 50（腰斩）→ 100（翻倍回本）
print(f"\n简单：跌 {(50 - 100) / 100:+.4f}，涨 {(100 - 50) / 50:+.4f}　← 一个 -50%，一个 +100%，看着像两回事")
print(f"对数：跌 {np.log(50 / 100):+.4f}，涨 {np.log(100 / 50):+.4f}　← 一正一负，完全对称")
print(f"而且两者相加 = {np.log(50 / 100) + np.log(100 / 50):+.4f} —— 对数收益里「跌回去再涨回来」就是回到原点")
# 简单收益率永远说不出这句话：-50% + 100% = +50%，明明回到了原点却算出来是赚的。


# ---- 4. 画出来：小波动贴合，大波动裂开 ----
# 手写一条 10 天的价格路径：前 4 天每天动 ±1%，后 5 天每天动 ±15%
moves = np.array([0.01, -0.01, 0.01, -0.01,    # 前段：小波动
                  0.15, -0.15, 0.15, -0.15, 0.15])   # 后段：大波动

# np.concatenate：把两段数组首尾接起来。这里在前面塞一个 1.0，
#   表示"第 0 天相对于自己没动"，好让第 0 天也有一个倍率。
# np.cumprod：累乘（cumulative product）—— 逐个乘起来，得到"从起点涨到今天是多少倍"。
prices = 100.0 * np.cumprod(np.concatenate([[1.0], 1.0 + moves]))
print(f"\n价格路径：{np.round(prices, 4)}")

r_simple = (prices[1:] - prices[:-1]) / prices[:-1]   # 29 个… 这里 10 天 → 9 个收益率
r_log = np.log(prices[1:] / prices[:-1])

# X 轴：第 1 天到第 9 天。为什么从 1 开始？第 0 天没有"前一天"，算不出收益率。
x = np.arange(1, len(prices))     # np.arange(1, 10) → [1,2,...,9]

# 乘 100 换成百分数。不换的话 Y 轴只有 ±0.15，而 plot() 会自动上下各留 1，
#   两条线会被压成贴着 0 的一条直线，什么都看不出来。
# np.column_stack：把两个一维数组按列拼成 (n, 2) 矩阵 —— plot() 的 point 层要的就是这个形状。
curve_simple = np.column_stack([x, r_simple * 100])
curve_log = np.column_stack([x, r_log * 100])

plot(
    [{"type": "point", "data": curve_simple, "color": "tab:blue", "s": 40},
     {"type": "point", "data": curve_log, "color": "tab:orange", "s": 40}],
    title="蓝 = 简单收益率，橙 = 对数收益率（%）：前段贴合，后段裂开",
)
